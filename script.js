/* ================= SCROLL REVEAL ================= */

const observer =
    new IntersectionObserver(
        entries => {

            entries.forEach(
                entry => {

                    if (
                        entry.isIntersecting
                    ) {

                        entry.target.classList.add(
                            "visible"
                        );

                        observer.unobserve(
                            entry.target
                        );

                    }

                }
            );

        },
        {
            threshold: 0.08
        }
    );


function observeReveal() {

    document
        .querySelectorAll(
            ".reveal:not(.visible)"
        )
        .forEach(element => {

            observer.observe(
                element
            );

        });

}


