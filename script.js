/* ================= ESCAPE HTML ================= */

function escapeHTML(value) {

    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");

}


/* ================= PROJECT RENDER ================= */

function renderProjects(filter = "all") {

    let projects;

    if (filter === "all") {

        projects = PROJECTS;

    } else {

        projects = PROJECTS.filter(
            project =>
                project.category.includes(filter)
        );

    }


    projectGrid.innerHTML = projects
        .map(project => {

            const index =
                PROJECTS.indexOf(project);


            const skills =
                project.skills.length

                    ?

                    project.skills
                        .map(
                            skill =>
                                `
                                <span class="skill-pill">
                                    ${escapeHTML(skill)}
                                </span>
                                `
                        )
                        .join("")

                    :

                    `
                    <span class="skill-pill">
                        Skills
                    </span>
                    `;


            const cover = project.cover

                ?

                `
                <img
                    src="${project.cover}"
                    alt="${escapeHTML(project.title)}"
                >
                `

                :

                `
                <div class="cover-placeholder">
                    PROJECT COVER
                </div>
                `;


            return `

                <article class="project-card reveal visible">

                    <div class="project-cover">
                        ${cover}
                    </div>

                    <div class="project-info">

                        <p class="project-category">
                            ${escapeHTML(project.categoryLabel)}
                        </p>

                        <h3>
                            ${escapeHTML(project.title)}
                        </h3>

                        <div class="card-skills">
                            ${skills}
                        </div>

                        <button
                            class="view-project"
                            data-index="${index}"
                        >

                            <span>
                                View Project
                            </span>

                            <span>
                                ↗
                            </span>

                        </button>

                    </div>

                </article>

            `;

        })
        .join("");


    document
        .querySelectorAll(".view-project")
        .forEach(button => {

            button.addEventListener(
                "click",
                () => {

                    openProject(
                        Number(button.dataset.index)
                    );

                }
            );

        });

}


/* ================= OPEN PROJECT ================= */

function openProject(index) {

    currentProject =
        PROJECTS[index];

    currentSlide = 0;


    modalCategory.textContent =
        currentProject.categoryLabel;


    modalTitle.textContent =
        currentProject.title;


    modalSummary.textContent =
        currentProject.summary;


    modalSkills.innerHTML =
        currentProject.skills
            .map(
                skill =>
                    `
                    <span class="skill-pill">
                        ${escapeHTML(skill)}
                    </span>
                    `
            )
            .join("");


    renderGallery();


    if (currentProject.link) {

        modalLink.href =
            currentProject.link;

        modalLink.classList.remove(
            "disabled"
        );

        modalLink.textContent =
            "View Project ↗";

    } else {

        modalLink.removeAttribute(
            "href"
        );

        modalLink.classList.add(
            "disabled"
        );

        modalLink.textContent =
            "Project link will be added later";

    }


    modal.classList.add("show");

    modal.setAttribute(
        "aria-hidden",
        "false"
    );

    document.body.classList.add(
        "modal-open"
    );

}


/* ================= CLOSE PROJECT ================= */

function closeProject() {

    modal.classList.remove("show");

    modal.setAttribute(
        "aria-hidden",
        "true"
    );

    document.body.classList.remove(
        "modal-open"
    );

}


/* ================= GALLERY ================= */

function renderGallery() {

    const images =
        currentProject.images || [];


    if (!images.length) {

        modalGallery.innerHTML = `

            <div class="modal-placeholder">

                <div>

                    <strong>
                        PROJECT IMAGES
                    </strong>

                    <br><br>

                    Add your real project
                    image filenames inside
                    the <b>images</b> array
                    in script.js.

                </div>

            </div>

        `;

        return;

    }


    modalGallery.innerHTML =
        images
            .map(
                (image, index) => `

                    <div
                        class="modal-slide
                        ${index === 0 ? "active" : ""}"
                    >

                        <img
                            src="${image}"
                            alt="${escapeHTML(
                                currentProject.title
                            )}"
                        >

                    </div>

                `
            )
            .join("");


    if (images.length > 1) {

        const controls = `

            <div class="carousel-buttons">

                <button id="prevImage">
                    ←
                </button>

                <button id="nextImage">
                    →
                </button>

            </div>

        `;

        modalGallery.insertAdjacentHTML(
            "beforeend",
            controls
        );


        document
            .getElementById("prevImage")
            .addEventListener(
                "click",
                () => changeSlide(-1)
            );


        document
            .getElementById("nextImage")
            .addEventListener(
                "click",
                () => changeSlide(1)
            );

    }

}


/* ================= CAROUSEL ================= */

function changeSlide(direction) {

    const total =
        currentProject.images.length;


    currentSlide =
        (currentSlide + direction + total)
        % total;


    updateSlide();

}


function updateSlide() {

    document
        .querySelectorAll(".modal-slide")
        .forEach((slide, index) => {

            slide.classList.toggle(
                "active",
                index === currentSlide
            );

        });

}


